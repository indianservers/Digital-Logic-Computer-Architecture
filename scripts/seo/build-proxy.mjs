import { build } from 'vite';

// The request entrypoint runs in Node, outside Vite's module loader. Bundle the
// shared URL mapper and JSON catalogue so no extensionless/JSON imports remain.
await build({
  configFile: false,
  publicDir: false,
  ssr: { noExternal: true },
  build: {
    ssr: 'src/seo/proxy.ts',
    // Keep the generated entrypoint in source control: Vercel may prepare its
    // middleware builder before the site's build command regenerates it.
    outDir: 'routing',
    emptyOutDir: true,
    minify: true,
    rollupOptions: {
      output: {
        entryFileNames: 'seo-proxy.mjs',
        banner: '/*! Generated by npm run seo:proxy from src/seo/proxy.ts. Do not edit directly. */',
      },
    },
  },
});
